"""
BMAD Integration for Revenue-First System

Automatically creates BMAD specs from high-ROI opportunities.
"""

import json
import os
from pathlib import Path
from typing import Dict, Optional
from datetime import datetime


class RevenueBMADIntegrator:
    """
    Integrates Revenue-First System with BMAD V2

    Takes high-ROI opportunities and creates BMAD specs that:
    - Include revenue tracking
    - Add synthetic test expectations
    - Track predicted vs actual revenue
    """

    def __init__(self, spec_dir: str = "auto-claude/specs"):
        self.spec_dir = Path(spec_dir)

    def create_spec_from_opportunity(
        self,
        opportunity: Dict,
        business_analysis: Dict,
        rank: int = 1
    ) -> str:
        """
        Create BMAD spec from revenue opportunity

        Args:
            opportunity: RevenueOpportunity dict
            business_analysis: BusinessAnalysis dict
            rank: Opportunity rank (for naming)

        Returns:
            Path to created spec directory
        """
        # Generate spec name
        feature_name = opportunity["feature"].lower().replace(" ", "-")
        spec_id = self._get_next_spec_id()
        spec_name = f"{spec_id:03d}-revenue-{feature_name}"
        spec_path = self.spec_dir / spec_name

        # Create spec directory
        spec_path.mkdir(parents=True, exist_ok=True)

        # Create spec.md
        spec_md = self._generate_spec_md(opportunity, business_analysis, rank)
        (spec_path / "spec.md").write_text(spec_md, encoding='utf-8')

        # Create requirements.json
        requirements = self._generate_requirements(opportunity, business_analysis)
        (spec_path / "requirements.json").write_text(
            json.dumps(requirements, indent=2),
            encoding='utf-8'
        )

        # Create revenue_tracking.json
        revenue_tracking = self._generate_revenue_tracking(opportunity)
        (spec_path / "revenue_tracking.json").write_text(
            json.dumps(revenue_tracking, indent=2),
            encoding='utf-8'
        )

        print(f"✅ Created BMAD spec: {spec_name}")
        print(f"   Path: {spec_path}")
        print(f"   Expected revenue: ${opportunity['potential_revenue_monthly']:,.0f}/mo")
        print(f"   Estimated effort: {opportunity['implementation_effort_days']:.1f} days")
        print(f"   ROI: ${opportunity['roi_score']:,.0f} per day")

        return str(spec_path)

    def _get_next_spec_id(self) -> int:
        """Get next available spec ID"""
        if not self.spec_dir.exists():
            return 1

        existing_specs = [
            d.name for d in self.spec_dir.iterdir()
            if d.is_dir() and d.name[0:3].isdigit()
        ]

        if not existing_specs:
            return 1

        max_id = max(int(s[:3]) for s in existing_specs)
        return max_id + 1

    def _generate_spec_md(
        self,
        opportunity: Dict,
        business_analysis: Dict,
        rank: int
    ) -> str:
        """Generate spec.md content"""
        feature = opportunity["feature"]
        description = opportunity["description"]
        competitors = ", ".join(opportunity["competitors_charging"])
        avg_price = opportunity["avg_competitor_price"]
        potential_revenue = opportunity["potential_revenue_monthly"]
        effort_days = opportunity["implementation_effort_days"]
        roi = opportunity["roi_score"]
        build_vs_buy = opportunity["build_vs_buy_recommendation"]

        libraries_section = ""
        if opportunity["github_libraries"]:
            libraries_section = "\n### Recommended Libraries\n\n"
            for lib in opportunity["github_libraries"]:
                libraries_section += f"- **{lib['name']}** ({lib['stars']:,} stars)\n"
                libraries_section += f"  {lib['description']}\n"
                libraries_section += f"  {lib['url']}\n\n"

        spec_md = f"""# {feature.title()}

**Revenue Opportunity #{rank}** - Generated by Revenue-First System

## Executive Summary

This feature represents a **${potential_revenue:,.0f}/mo revenue opportunity** based on competitor analysis.

- **Competitors charging for this**: {competitors}
- **Average competitor price**: ${avg_price:.2f}/mo per user
- **Estimated effort**: {effort_days:.1f} days
- **ROI**: ${roi:,.0f} per day
- **Recommendation**: {build_vs_buy}

## Business Context

### Current State
- Your MRR: ${business_analysis['revenue_model']['current_mrr']:,.2f}
- Active Subscriptions: {business_analysis['revenue_model']['active_subscriptions']}
- Revenue Model: {business_analysis['revenue_model']['type'].title()}

### Target State
- New MRR: ${business_analysis['revenue_model']['current_mrr'] + potential_revenue:,.2f}
- Growth: +{(potential_revenue / max(business_analysis['revenue_model']['current_mrr'], 1) * 100):.1f}%

## Feature Description

{description}

### Why This Feature?

{len(opportunity['competitors_charging'])} competitors charge for this feature, indicating:
1. Market demand exists
2. Customers are willing to pay for it
3. It's a proven revenue driver

## Implementation Approach

{build_vs_buy}
{libraries_section}
## Acceptance Criteria

### Functional Requirements
1. Feature matches competitor offerings
2. Integrates with existing pricing tiers
3. Usage tracking enabled
4. Analytics dashboard shows adoption

### Revenue Requirements
1. Feature available in paid tiers only
2. Pricing matches or beats competitor average
3. Revenue tracking enabled from day 1
4. A/B testing framework ready

### Quality Requirements
1. Unit test coverage > 80%
2. Integration tests for critical paths
3. Load testing for scalability
4. Security audit completed

## Revenue Validation

### Success Metrics
- **Target adoption rate**: 20% of existing users
- **Target revenue**: ${potential_revenue:,.0f}/mo within 60 days
- **Target upgrade rate**: 15% of free users

### Tracking Plan
- Weekly revenue reports
- Daily adoption tracking
- User feedback surveys
- A/B test results

## Risks & Mitigation

### Technical Risks
- Integration complexity
- Performance impact
- Security vulnerabilities

**Mitigation**: Use battle-tested libraries, comprehensive testing, security review

### Business Risks
- Lower than expected adoption
- Competitor response
- Customer churn

**Mitigation**: Start with beta group, iterate based on feedback, monitor churn closely

## Timeline

- **Planning**: 0.5 days
- **Implementation**: {effort_days:.1f} days
- **Testing**: 1 day
- **Beta rollout**: 3 days
- **Full launch**: 7 days

**Total**: {effort_days + 4.5:.1f} days

## Next Steps

1. Run this spec (revenue tracking auto-detected): `python auto-claude/run.py --spec {self._get_next_spec_id():03d}`
2. Review generated architecture
3. Approve implementation plan
4. Monitor revenue after launch

---

*This spec was auto-generated from revenue opportunity analysis. Predicted revenue is based on competitor pricing and conservative adoption estimates.*
"""
        return spec_md

    def _generate_requirements(
        self,
        opportunity: Dict,
        business_analysis: Dict
    ) -> Dict:
        """Generate requirements.json"""
        return {
            "feature_name": opportunity["feature"],
            "description": opportunity["description"],
            "priority": "high",
            "complexity": "standard",
            "revenue_opportunity": {
                "potential_monthly": opportunity["potential_revenue_monthly"],
                "effort_days": opportunity["implementation_effort_days"],
                "roi_score": opportunity["roi_score"],
                "competitors_charging": opportunity["competitors_charging"],
                "avg_competitor_price": opportunity["avg_competitor_price"]
            },
            "business_context": {
                "current_mrr": business_analysis["revenue_model"]["current_mrr"],
                "active_subscriptions": business_analysis["revenue_model"]["active_subscriptions"],
                "revenue_model": business_analysis["revenue_model"]["type"]
            },
            "implementation": {
                "build_vs_buy": opportunity["build_vs_buy_recommendation"],
                "github_libraries": opportunity["github_libraries"]
            },
            "acceptance_criteria": [
                "Feature matches competitor offerings",
                "Revenue tracking enabled",
                f"Target revenue: ${opportunity['potential_revenue_monthly']:,.0f}/mo within 60 days",
                "Unit test coverage > 80%",
                "Security audit passed"
            ],
            "created_at": datetime.now().isoformat(),
            "created_by": "revenue-first-system"
        }

    def _generate_revenue_tracking(self, opportunity: Dict) -> Dict:
        """Generate revenue_tracking.json for post-launch monitoring"""
        return {
            "opportunity_id": opportunity["feature"].lower().replace(" ", "_"),
            "predicted": {
                "monthly_revenue": opportunity["potential_revenue_monthly"],
                "effort_days": opportunity["implementation_effort_days"],
                "roi_score": opportunity["roi_score"],
                "predicted_at": datetime.now().isoformat()
            },
            "actual": {
                "monthly_revenue": 0.0,
                "adoption_rate": 0.0,
                "upgrade_rate": 0.0,
                "completed_at": None
            },
            "tracking": {
                "enabled": True,
                "start_date": None,
                "milestones": [
                    {"day": 7, "target_revenue": opportunity["potential_revenue_monthly"] * 0.1},
                    {"day": 30, "target_revenue": opportunity["potential_revenue_monthly"] * 0.5},
                    {"day": 60, "target_revenue": opportunity["potential_revenue_monthly"]}
                ],
                "actual_milestones": []
            },
            "validation": {
                "accuracy_score": None,
                "notes": []
            }
        }


def main():
    """CLI entry point for BMAD integration"""
    import argparse

    parser = argparse.ArgumentParser(description="Create BMAD spec from revenue opportunity")
    parser.add_argument("--opportunity-file", required=True, help="Opportunity report JSON file")
    parser.add_argument("--business-file", required=True, help="Business analysis JSON file")
    parser.add_argument("--rank", type=int, default=1, help="Opportunity rank to use (1 = highest ROI)")
    parser.add_argument("--spec-dir", default="auto-claude/specs", help="Specs directory")

    args = parser.parse_args()

    # Load opportunity report
    with open(args.opportunity_file, 'r', encoding='utf-8') as f:
        opp_report = json.load(f)

    # Load business analysis
    with open(args.business_file, 'r', encoding='utf-8') as f:
        business = json.load(f)

    # Get opportunity by rank
    if args.rank < 1 or args.rank > len(opp_report["opportunities"]):
        print(f"Error: Rank {args.rank} out of range (1-{len(opp_report['opportunities'])})")
        return

    opportunity = opp_report["opportunities"][args.rank - 1]

    # Create spec
    integrator = RevenueBMADIntegrator(spec_dir=args.spec_dir)
    spec_path = integrator.create_spec_from_opportunity(
        opportunity=opportunity,
        business_analysis=business,
        rank=args.rank
    )

    print(f"\n✅ BMAD spec created successfully!")
    print(f"\nNext steps:")
    spec_id = Path(spec_path).name.split("-")[0]
    print(f"  1. Review spec: cat {spec_path}/spec.md")
    print(f"  2. Run BMAD (auto-detects revenue tracking): python auto-claude/run.py --spec {spec_id}")
    print(f"  3. Track revenue: cat {spec_path}/revenue_tracking.json")


if __name__ == "__main__":
    main()
